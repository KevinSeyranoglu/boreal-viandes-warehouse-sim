"""Train and evaluate every model, write ml/results/metrics.json and ml/RESULTS.md.

    python ml/train_all.py                 # uses data/warehouse.db (all scenarios in it)

Each model is compared with the simple method a distribution center uses today, on days the model
never saw (time-based split). RESULTS.md is generated: never edit the numbers by hand.
"""
from __future__ import annotations

import json
import os
import sys
import time

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import common as cm  # noqa: E402
import demand  # noqa: E402
import labour  # noqa: E402
import late_orders  # noqa: E402
import spoilage  # noqa: E402
import temperature  # noqa: E402


def clean(d):
    out = {}
    for k, v in d.items():
        if isinstance(v, (pd.DataFrame,)):
            continue
        if isinstance(v, pd.Series):
            v = {i: round(float(x), 4) for i, x in v.items()}
        elif isinstance(v, dict):
            v = clean(v)
        elif isinstance(v, float):
            v = round(v, 4)
        out[k] = v
    return out


def run_all(db=None, out_dir=None, plot=True):
    con = cm.connect(db)
    t0 = time.time()
    res = {}
    res["demand"] = demand.run(con, plot=plot)
    res["labour"] = labour.run(con, plot=plot, demand_res=res["demand"])
    res["spoilage"] = spoilage.run(con, plot=plot)
    res["late_orders"] = late_orders.run(con, plot=plot)
    res["temperature"] = temperature.run(con, plot=plot)
    out = {k: clean(v) for k, v in res.items()}
    out_dir = out_dir or os.path.join(HERE, "results")
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "metrics.json"), "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=2, default=str)
    write_results_md(out, os.path.join(os.path.dirname(out_dir), "RESULTS.md") if out_dir.endswith("results")
                     else os.path.join(out_dir, "RESULTS.md"))
    print(f"trained 5 models in {time.time() - t0:.0f} s -> {out_dir}")
    return out


def pct(v, d=1):
    return f"{v * 100:.{d}f} %"


def money(v):
    return "–" if v is None else (f"${v:,.0f}" if v >= 0 else f"-${-v:,.0f}")


def write_results_md(r, path):
    L = ["# Model results (generated by `ml/train_all.py`; do not edit by hand)", "",
         "Test period: the last third of each 180-day run (days the models never saw). "
         "Value per day = model's net benefit minus the baseline's, under the assumptions in each model card "
         "([README](README.md)).", "",
         "| Model | Metric | Model | Baseline | Value / day |", "|---|---|---|---|---|"]
    d, lb, sp, lo, te = (r[k] for k in ("demand", "labour", "spoilage", "late_orders", "temperature"))
    if "skipped" not in d:
        L.append(f"| Demand forecast | WAPE, store × SKU × day | {pct(d['wape_store_sku'])} | {pct(d['wape_store_sku_baseline'])} "
                 f"(same weekday last week) | {money(d['value_per_day'])} |")
        L.append(f"| | WAPE, SKU × day | {pct(d['wape_sku_day'])} | {pct(d['wape_sku_day_baseline'])} | |")
    if "skipped" not in lb:
        L.append(f"| Labour planning | picker-hours / day | {lb['plan']['hours_per_day']:.0f} | {lb['fixed']['hours_per_day']:.0f} "
                 f"(fixed crew) | {money(lb['value_per_day'])} |")
        L.append(f"| | expected late orders / day | {lb['plan']['expected_late_orders_per_day']:.2f} | "
                 f"{lb['fixed']['expected_late_orders_per_day']:.2f} | |")
    if "skipped" not in sp:
        L.append(f"| Spoilage risk | PR-AUC | {sp['pr_auc']:.2f} | {sp['pr_auc_rule']:.2f} ({sp['baseline']}) | "
                 f"{money(sp['value_per_day'])} |")
        L.append(f"| | precision / recall at the chosen threshold | {pct(sp['precision_model'], 0)} / {pct(sp['recall_model'], 0)} | "
                 f"{pct(sp['precision_rule'], 0)} / {pct(sp['recall_rule'], 0)} | **rule recommended** |")
    if "skipped" not in lo:
        L.append(f"| Late-order risk | PR-AUC | {lo['pr_auc']:.2f} | {lo['pr_auc_rule']:.2f} (largest orders) | "
                 f"{money(lo['value_per_day'])} |")
        L.append(f"| | late orders caught / precision | {pct(lo['recall_model'], 0)} / {pct(lo['precision_model'], 0)} | "
                 f"{pct(lo['recall_rule'], 0)} / {pct(lo['precision_rule'], 0)} | |")
    if "skipped" not in te:
        L.append(f"| Cold-room early warning | average warning lead | {te['lead_min_model']:.0f} min | {te['lead_min_rule']:.0f} min "
                 f"({te['baseline']}) | not monetised |")
        L.append(f"| | flagged readings / day, breaches warned | {te['warnings_per_day_model']:.1f}, {pct(te['breaches_warned_model'], 0)} | "
                 f"{te['warnings_per_day_rule']:.1f}, {pct(te['breaches_warned_rule'], 0)} | |")
    skipped = [k for k, v in r.items() if "skipped" in v]
    if skipped:
        L += ["", "Skipped (too few positive cases in this run): " + ", ".join(skipped)]
    L += ["", "Figures: `ml/figures/`."]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")


if __name__ == "__main__":
    run_all(sys.argv[1] if len(sys.argv) > 1 else None)
